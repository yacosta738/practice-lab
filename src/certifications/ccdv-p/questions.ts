type SourceKey = keyof typeof sources;

function createQuestion(
	id: string,
	domain: string,
	question: string,
	options: string[],
	correctAnswers: number[],
	explanation: string,
	sourceKey: SourceKey,
): Question {
	return {
		id,
		domain,
		question,
		options,
		correctAnswers,
		explanation,
		source: sources[sourceKey],
		...(correctAnswers.length > 1 ? { selectCount: correctAnswers.length } : {}),
	};
}

